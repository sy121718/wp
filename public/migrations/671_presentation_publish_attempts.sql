-- 671 · 发布尝试明细（商品发布历史）。
--
-- 背景：发布失败的路径什么都不留 —— 事务整体回滚，presentation_artifacts 里连产物行
-- 都不会有。于是「我昨晚发了三次，为什么线上还是旧版」这个问题没有数据可答。
-- presentation_artifacts 记的是**成功的字节**（版本单调 +1，已有），本表记的是
-- **每次尝试**（含失败），两者互补：
--
--   artifacts  回答「这个页面发布过哪几版，每版是什么」
--   本表        回答「每次谁在什么时候、因为什么发了 / 没发出去」
--
-- 与 publication_receipts 的区别：那张是访问面切换的补偿台账（pending / committed /
-- rolled_back，只覆盖切换那一段，完成后只留终态，且是给恢复逻辑用的），不是给人看的
-- 发布日志。两者互不替代。
--
-- 写入点：publishAllLangs 的 defer（事务外）。**不能同事务** —— 失败时事务回滚，
-- 本表要留的正是那条失败记录。代价：进程被 kill 时最后一条会丢，这是拿「记录完整」
-- 换「记录必然存在」的取舍。
--
-- 不设保留策略（用户明确要求全留）：表只增，读侧靠「默认最近 10 条 + 游标加载更多」，
-- 而不是靠删。查询走 (instance_id, create_time DESC) 与 (project_id, create_time DESC)。

CREATE TABLE IF NOT EXISTS presentation_publish_attempts (
    id               bigint generated by default as identity PRIMARY KEY,
    project_id       uuid NOT NULL,
    instance_id      uuid NOT NULL,
    entity_type      text NOT NULL,
    entity_id        uuid NOT NULL,
    -- trigger 本次发布的触发源。自动重建与人工发布要能分开看：
    -- 一次依赖变更会重建几十个实例，混在人工发布里会淹掉人真正关心的那几条。
    trigger          text NOT NULL,
    -- outcome success / failed。失败行的 error_text 是给人看的原文（不含堆栈）。
    outcome          text NOT NULL,
    error_text       text NOT NULL DEFAULT '',
    -- langs 本次涉及的语言（成功时 = 实际发布的语言，失败时 = 尝试发布的范围）。
    langs            text[] NOT NULL DEFAULT '{}',
    -- attempts 冲突重试次数（PERF-01 的分阶段指标同源）：>1 说明编译被丢弃重来过。
    attempts         integer NOT NULL DEFAULT 1,
    -- 成功后指向产物；失败时 0 / 空串。
    artifact_version bigint NOT NULL DEFAULT 0,
    artifact_hash    text NOT NULL DEFAULT '',
    -- 操作人快照列：账号被删或改名后，历史仍要能回答「当时是谁点的」。
    -- 0 / 空串 = 系统触发（自动重建没有用户上下文）。
    operator_id      bigint NOT NULL DEFAULT 0,
    operator_name    text NOT NULL DEFAULT '',
    duration_ms      bigint NOT NULL DEFAULT 0,
    create_time      timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT ck_publish_attempts_outcome CHECK (outcome IN ('success', 'failed')),
    CONSTRAINT ck_publish_attempts_trigger CHECK (trigger IN (
        'create', 'manual', 'template_switch', 'update_url', 'rollback',
        'override', 'auto_rebuild'
    )),
    CONSTRAINT ck_publish_attempts_attempts CHECK (attempts >= 1),
    CONSTRAINT ck_publish_attempts_duration CHECK (duration_ms >= 0)
);

-- 读口的主查询：某实例的历史，倒序游标分页。
CREATE INDEX IF NOT EXISTS idx_publish_attempts_instance
    ON presentation_publish_attempts (instance_id, create_time DESC, id DESC);

-- 读口的主查询之二：某实体的历史（商品发布历史抽屉按 product_id 读，
-- 一个实体可能有两张页面实例 —— detail / archive，所以按 entity 而不是 instance 读）。
CREATE INDEX IF NOT EXISTS idx_publish_attempts_entity
    ON presentation_publish_attempts (entity_type, entity_id, create_time DESC, id DESC);

-- 按工程看全站发布活动（本期页面不用，但排障时会问「这个工程最近发过什么」）。
CREATE INDEX IF NOT EXISTS idx_publish_attempts_project
    ON presentation_publish_attempts (project_id, create_time DESC, id DESC);

COMMENT ON TABLE presentation_publish_attempts IS '每一次发布尝试的明细（含失败）：谁、何时、因何、成否。发布失败的路径只能靠本表留痕';
COMMENT ON COLUMN presentation_publish_attempts.trigger IS '触发源：create/manual/template_switch/update_url/rollback/override/auto_rebuild';
COMMENT ON COLUMN presentation_publish_attempts.outcome IS '结局：success 产出了新产物 / failed 未产出（error_text 记原因）';
COMMENT ON COLUMN presentation_publish_attempts.attempts IS '冲突重试次数：>1 表示有编译结果被丢弃重来（PERF-01 指标同源）';
COMMENT ON COLUMN presentation_publish_attempts.operator_name IS '操作人姓名快照（0/空串 = 系统触发）；账号删除后历史仍可读';

-- RLS：工程维度，与 215 / 627 / 630 同口径（fail closed）。
-- 215 的名单是快照（用 information_schema 枚举当时已存在的表），本表后来新建，
-- 不在这里显式加就等于任何工程都能读别人的发布历史。
ALTER TABLE presentation_publish_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE presentation_publish_attempts FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS project_isolation ON presentation_publish_attempts;
CREATE POLICY project_isolation ON presentation_publish_attempts
    USING (project_id = NULLIF(current_setting('app.project_id', true), '')::uuid)
    WITH CHECK (project_id = NULLIF(current_setting('app.project_id', true), '')::uuid);
