-- 480 · 删除已退役的「未选择图片」词条（admin.common.media.empty）。
--
-- 背景：媒体字段的空态从一句文案改成了一个「＋」——一个图片框要做什么，看形状就知道，
--   写「尚未选择图片」只是把同一件事说了第二遍，还多一条要翻译的词条。
--   代码侧已无任何引用，这两行成了孤儿。
--
-- **为什么要连 432 一起收口**（不是只删库里那两行）：
--   432 的 seed 门槛是「本批 71 个 key 的 en-US 行都在」，而它**枚举的列表里就有这个 key**。
--   只删数据不改门槛，删除后的计数（70）永远小于门槛（71）→ 每次启动 432 都会重跑 →
--   ON CONFLICT DO NOTHING 不生效（行已经没了）→ 把这两行**插回来**。
--   这是仓库里有真实先例的坑（122 / 104）。所以本批同时改了：
--     ① 432 的 SQL（不再 INSERT 这两行）；
--     ② 432 门槛的 key 列表与计数（71 → 70）；
--     ③ 这里删掉库里已有的那两行。
--
-- 幂等：DELETE 的结果与执行次数无关；门槛要求库里已经没有这两行。
DELETE FROM sys_i18n WHERE item_key = 'admin.common.media.empty';
