-- 211 · 删除区块 id 映射表 block_id_uuid_map。
--
-- 背景：209 把 blocks.id 从 bigint 换回 uuid 时建了这张旧→新映射表，用途是
-- 「查询哪个块换了哪个 id」的审计痕迹。现在它的使命已经结束：
--   · 209 的判定按「blocks.id 已是 uuid」，**不读这张表** —— 删掉不会让 209 重跑；
--   · 全库实测 0 行 —— 迁移执行时开发库的 blocks 本就是空的，映射从未产生过内容；
--   · 代码侧只有 209 的 SQL 与一个单测引用它，没有任何运行时读路径。
-- 留着一张永远为空、没有人查的表，只会让后来者以为存在「按旧 id 反查」的能力。
--
-- 幂等：判定按「表已不存在」。
-- 空库重放时的顺序是 209 建表（映射为空）→ 211 删除，净效果正确。

DROP TABLE IF EXISTS block_id_uuid_map;
